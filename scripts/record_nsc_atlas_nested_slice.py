"""Record one two-level nested initial slice. Run only after the method is frozen."""
from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
import subprocess
import time

from recursive_horizons.nsc_atlas_nested_slice import CPU_SECONDS, SAMPLE_LIMIT, nested_slice_record
from recursive_horizons.nsc_atlas_nested_spacetime import central_inward_flash, regular_kottler_chart


ROOT = Path(__file__).resolve().parents[1]
SOURCE_PATHS = (
    "scripts/record_nsc_atlas_nested_slice.py",
    "scripts/plot_nsc_atlas_nested_slice.py",
    "src/recursive_horizons/nsc_atlas_nested_slice.py",
    "tests/test_nsc_atlas_nested_slice.py",
    "src/recursive_horizons/nsc_atlas_nested_spacetime.py",
    "tests/test_nsc_atlas_nested_spacetime.py",
    "src/recursive_horizons/nsc_atlas_connection_slice.py",
    "src/recursive_horizons/nsc_atlas_geometric_average.py",
)
BYTE_LIMIT = 30_000


def frozen_sources():
    commit = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
    hashes = {}
    for name in SOURCE_PATHS:
        raw = (ROOT/name).read_bytes()
        try:
            committed = subprocess.check_output(["git", "show", f"{commit}:{name}"], cwd=ROOT)
        except subprocess.CalledProcessError as error:
            raise ValueError("nested-slice source is not frozen: "+name) from error
        if raw != committed:
            raise ValueError("nested-slice source is not frozen: "+name)
        hashes[name] = hashlib.sha256(raw).hexdigest()
    return commit, hashes


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    if args.output.exists():
        raise FileExistsError("use a fresh output path; retained results are not overwritten")
    if not args.output.parent.is_dir():
        raise ValueError("output parent directory must exist")
    started = time.process_time()
    commit, hashes = frozen_sources()
    record = nested_slice_record(1.0)
    inner = record["walls"]["inner"]
    flash = central_inward_flash(radius=inner["R_over_ell"],H=1.,
                                beta_minus=inner["beta_minus"],Rdot=inner["Rdot"])
    # Independent exact rational factors and high-precision evaluation of the
    # previously derived protocol; this is a roundoff check, not a data fit.
    import mpmath as mp
    with mp.workdps(80):
        beta = mp.mpf(517)/640
        rate = mp.sqrt(beta*beta-mp.mpf(9)/25)
        exact_time = mp.log(5)
        exact_ratio = mp.mpf(25)/9*(beta+rate)
        time_difference = float(abs(mp.mpf(flash["central_proper_time"])-exact_time))
        ratio_difference = float(abs(mp.mpf(flash["one_plus_redshift"])-exact_ratio))
    if max(time_difference,ratio_difference)>2e-13:
        raise ValueError("central flash differs from independent exact factors")
    ell_m = 10_000.
    record["central_flash"] = {
        **flash, "physical_ruler_m":ell_m, "ruler_is_supplied":True,
        "arrival_seconds_at_supplied_ruler":flash["central_proper_time"]*ell_m/299_792_458.,
        "closed_form_arrival_over_ell":"log(5)",
        "closed_form_one_plus_z":"25/9*(517/640+sqrt((517/640)^2-9/25))",
        "high_precision_time_absolute_difference_over_ell":time_difference,
        "high_precision_one_plus_z_absolute_difference":ratio_difference,
        "precision_is_model_or_observational_uncertainty":False,
        "emission_frequency":"prescribed ideal wall proper-frequency standard; not generated by the tension action",
        "causal_scope":"cap-side flash; no outer-wall transmission through the host bridge",
    }
    charts=[]
    for C in (record["horizons"]["host_rb_over_ell"],record["horizons"]["host_rc_over_ell"]):
        # The two axes and their intersection are finite regular bulk tests.
        # Their coordinate points do not identify distinct physical patches.
        chart=regular_kottler_chart([0.,.2,0.],[.2,0.,0.],mass=.01,H=1.,horizon=C)
        charts.append({"horizon_over_ell":C,"kappa_times_ell":chart["kappa"],
                       "metric_determinant":chart["radial_metric_determinant"],
                       "root_residual":chart["horizon_root_residual"],
                       "chart_mass_roundoff_difference_over_ell":chart["mass_roundoff_difference"]})
    record["regular_host_bulk_charts"]={"checks":charts,
        "matched_two_wall_clock_constructed":False,
        "scope":"separate regular bulk charts, not a global identification or completed source atlas"}
    record["geometric_evaluations"]+=7
    elapsed = time.process_time()-started
    if record["geometric_evaluations"] > SAMPLE_LIMIT or elapsed > CPU_SECONDS:
        raise RuntimeError("nested-slice application exceeded its budget")
    if record["assumptions"]["scalar_field_solves"] != 0 or record["assumptions"]["evolution_steps"] != 0:
        raise RuntimeError("nested-slice application performed a field step")
    payload = {
        "method_commit": commit,
        "source_sha256": hashes,
        "command": "python scripts/run_python.py scripts/record_nsc_atlas_nested_slice.py --output <path>",
        "runtime_cpu_seconds": elapsed,
        "record": record,
    }
    text = json.dumps(payload, indent=2, sort_keys=True, allow_nan=False)+"\n"
    if len(text.encode("utf-8")) > BYTE_LIMIT:
        raise ValueError("nested-slice record exceeds 30KB")
    if not math.isfinite(record["moments"]["volume_over_ell3"]):
        raise ValueError("nested-slice moments are not finite")
    args.output.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {args.output}; {elapsed:.3f} CPU seconds; "
          f"{record['geometric_evaluations']} geometric evaluations; no evolution.")


if __name__ == "__main__":
    main()
